import { v } from "convex/values";

const curvePolicyValidator = v.union(
  v.object({ mode: v.literal("fixed"), value: v.number() }),
  v.object({ mode: v.literal("linear"), from: v.number(), to: v.number() }),
  v.object({
    mode: v.literal("step"),
    start: v.number(),
    increment: v.number(),
    cap: v.optional(v.number()),
  }),
  v.object({
    mode: v.literal("randomRange"),
    min: v.number(),
    max: v.number(),
    seedMode: v.optional(v.union(v.literal("session"), v.literal("level"))),
  })
);

const budgetPolicyValidator = v.object({
  mode: v.literal("budget"),
  count: v.number(),
  distribution: v.union(
    v.literal("even"),
    v.literal("random"),
    v.literal("early"),
    v.literal("late"),
    v.literal("manual")
  ),
  levels: v.optional(v.array(v.number())),
});

export const levelBandPolicyValidator = v.object({
  id: v.string(),
  fromLevel: v.number(),
  toLevel: v.number(),
  asteroidCount: curvePolicyValidator,
  asteroidSpeed: curvePolicyValidator,
  shipPickups: budgetPolicyValidator,
  powerups: budgetPolicyValidator,
  maxLives: curvePolicyValidator,
  chaos: v.optional(v.object({ enabled: v.boolean() })),
});

export const progressionBandsValidator = v.array(levelBandPolicyValidator);

